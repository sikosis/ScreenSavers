const GlyphPattern*
find_pattern(char character)
{
	const char upper = static_cast<char>(std::toupper(
		static_cast<unsigned char>(character)));
	for (const GlyphPattern& pattern : kPatterns) {
		if (pattern.character == upper)
			return &pattern;
	}
	for (const GlyphPattern& pattern : kPatterns) {
		if (pattern.character == '?')
			return &pattern;
	}
	return nullptr;
}
