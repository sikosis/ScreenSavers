int32_t
BuildTextCells(const std::string& text, std::vector<TextCell>& cells)
{
	cells.clear();
	int32_t totalColumns = 0;
	for (std::size_t index = 0; index < text.size(); index++) {
		const GlyphPattern* pattern = find_pattern(text[index]);
		if (pattern == nullptr)
			continue;
		for (int32_t column = 0; column < pattern->width; column++) {
			for (int32_t row = 0; row < kTextRows; row++) {
				if (pattern->rows[row][column] == '1')
					cells.push_back({totalColumns + column, row});
			}
		}
		totalColumns += pattern->width;
		if (index + 1 < text.size())
			totalColumns++;
	}
	return totalColumns;
}
